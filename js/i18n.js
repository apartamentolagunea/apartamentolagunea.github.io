// Spanish texts are read from the DOM once, so switching back is lossless.
const ES = {};
document.querySelectorAll("[data-i18n]").forEach(el => { ES[el.dataset.i18n] = el.textContent; });
T.es = ES;

function setLang(lang) {
  if (!T[lang]) lang = "es";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const s = T[lang][el.dataset.i18n];
    if (s !== undefined) el.textContent = s;
  });
  document.documentElement.lang = lang;
  document.querySelector('meta[name="description"]').setAttribute("content", META[lang].desc);
  document.querySelectorAll(".lang button").forEach(b => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  try { localStorage.setItem("lagunea-lang", lang); } catch (e) {}
}

document.querySelectorAll(".lang button").forEach(b => b.addEventListener("click", () => setLang(b.dataset.lang)));

(function init() {
  let saved = null;
  try { saved = localStorage.getItem("lagunea-lang"); } catch (e) {}
  const fromUrl = new URLSearchParams(location.search).get("lang");
  const browser = (navigator.language || "es").slice(0, 2).toLowerCase();
  setLang(fromUrl || saved || (T[browser] ? browser : "es"));
})();
